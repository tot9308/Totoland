function P(r: string): SpeciesCard {
  const c = r.split("|")
  return {
    common: c[0],
    sci: c[1],
    light: Number(c[2]) as 1 | 2 | 3 | 4,
    water: c[3] as "A" | "B" | "C",
    temp: c[4],
    mist: c[5] as "Sí" | "Mod" | "No",
    substrate: c[6] === "-" ? 0 : Number(c[6]),
    fert: c[7],
    toxic: c[8] === "1",
    difficulty: Number(c[9]) as 1 | 2 | 3,
    ws: Number(c[10]),
    ww: Number(c[11]),
    flags: c[12] ?? "",
    aliases: c[13] ?? "",

  }
}

